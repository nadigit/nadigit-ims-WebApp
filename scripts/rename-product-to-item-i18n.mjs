function transformValue(lang, key, value) {
  if (typeof value !== 'string' || EXCLUDED_KEYS.has(key)) {
    return value;
  }
  // Preserve {{product}} interpolation token spelling in template strings.
  const token = '__PLACEHOLDER_PRODUCT__';
  let next = value.replace(/\{\{product\}\}/g, token).replace(/\{product\}/g, token);
  for (const [pattern, replacement] of LANG_RULES[lang]) {
    next = next.replace(pattern, replacement);
  }
  return next.replaceAll(token, '{{product}}');
}

function processFile(lang) {
  const filePath = join(i18nDir, `${lang}.json`);
  const data = JSON.parse(readFileSync(filePath, 'utf8'));
  let changed = 0;
  for (const [key, value] of Object.entries(data)) {
    const updated = transformValue(lang, key, value);
    if (updated !== value) {
      data[key] = updated;
      changed++;
    }
  }
  writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.log(`${lang}.json: updated ${changed} strings`);
}

for (const lang of ['en', 'fr', 'es', 'ar']) {
  processFile(lang);
}
